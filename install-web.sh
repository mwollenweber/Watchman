#!/bin/bash
# Installs Watchman as a web-only host: the Django site under gunicorn, run as a
# systemd service that starts on boot. Nothing else: no Postgres, no Redis, no
# daily ingest. The host points at a database that is always up (DBHOST in the
# config), typically shared with the ingest instance.

SERVICE_NAME="watchman-web"
UNIT_FILE="/etc/systemd/system/$SERVICE_NAME.service"
APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() {
    echo "Usage: sudo $0 [--config FILE] [--user USER] [--dry-run]"
    echo "       sudo $0 --uninstall"
    echo "  --config FILE  Config file for the service (default: config.rc)"
    echo "  --user USER    User the service runs as (default: the user who ran sudo)"
    echo "  --dry-run      Print what would be installed without changing anything"
    echo "  --uninstall    Stop, disable and remove the service"
    echo
    echo "Config settings used: DBHOST/DBNAME/DBUSER/DBPASSWORD, BASE_URL, WEB_BIND,"
    echo "WEB_WORKERS, DJANGO_SECRET_KEY (generated if missing), ALLOWED_HOSTS."
}

CONFIG=""
RUN_USER="${SUDO_USER:-$(id -un)}"
DRY_RUN=0
UNINSTALL=0
while [ $# -gt 0 ]; do
    case "$1" in
        --config) CONFIG="$2"; shift ;;
        --user) RUN_USER="$2"; shift ;;
        --dry-run) DRY_RUN=1 ;;
        --uninstall) UNINSTALL=1 ;;
        -h|--help) usage; exit 0 ;;
        *) echo "Unknown option: $1"; usage; exit 1 ;;
    esac
    shift
done

if [ $DRY_RUN -eq 0 ]; then
    if ! command -v systemctl >/dev/null 2>&1; then
        echo "Error: systemd is required (systemctl not found)."
        exit 1
    fi
    if [ "$(id -u)" -ne 0 ]; then
        echo "Error: run this with sudo; it installs packages and writes to /etc/systemd/system."
        exit 1
    fi
fi

if [ $UNINSTALL -eq 1 ]; then
    systemctl stop "$SERVICE_NAME.service" 2>/dev/null
    systemctl disable "$SERVICE_NAME.service" 2>/dev/null
    rm -f "$UNIT_FILE"
    systemctl daemon-reload
    echo "Removed $SERVICE_NAME.service"
    exit 0
fi

if [ "$RUN_USER" = "root" ]; then
    echo "Error: refusing to run Watchman as root. Use --user, or run this script with sudo from your normal account."
    exit 1
fi
if ! id "$RUN_USER" >/dev/null 2>&1; then
    echo "Error: user $RUN_USER doesn't exist."
    exit 1
fi

# run-web.sh sources the config relative to APP_DIR
CONFIG="${CONFIG:-config.rc}"
case "$CONFIG" in
    /*) ;;
    *) CONFIG="$APP_DIR/$CONFIG" ;;
esac
if [ ! -f "$CONFIG" ]; then
    echo "Error: config file $CONFIG not found. Copy example-config.rc and fill it in."
    exit 1
fi

# Read the config in a subshell so its exports don't leak into this script
config_value() {
    ( source "$CONFIG" >/dev/null 2>&1; printf '%s' "${!1}" )
}

for var in DBHOST DBNAME DBUSER DBPASSWORD BASE_URL; do
    if [ -z "$(config_value $var)" ]; then
        echo "Error: $var is not set in $CONFIG."
        exit 1
    fi
done
if [ "$(config_value DBHOST)" = "localhost" ] || [ "$(config_value DBHOST)" = "127.0.0.1" ]; then
    echo "Warning: DBHOST is localhost but this script doesn't install Postgres."
    echo "         Point DBHOST at a database that is up whenever this host is."
fi
case "$(config_value DEBUG)" in
    1|true|TRUE|True|yes|on)
        echo "Warning: DEBUG is on in $CONFIG. The site will show debug pages and serve static files unminified."
        ;;
esac

BIND="$(config_value WEB_BIND)"
BIND="${BIND:-0.0.0.0:8000}"
PORT="${BIND##*:}"

unit="[Unit]
Description=Watchman web service (Django under gunicorn)
Wants=network-online.target
After=network-online.target

[Service]
User=$RUN_USER
WorkingDirectory=$APP_DIR
ExecStart=/bin/bash \"$APP_DIR/run-web.sh\" \"$CONFIG\"
Restart=always
RestartSec=5
KillMode=mixed
TimeoutStopSec=30"

# Binding a privileged port needs CAP_NET_BIND_SERVICE
if [ "$PORT" -lt 1024 ] 2>/dev/null; then
    unit="$unit
AmbientCapabilities=CAP_NET_BIND_SERVICE"
fi

unit="$unit

[Install]
WantedBy=multi-user.target"

if [ $DRY_RUN -eq 1 ]; then
    echo "# Would: install Python if needed, build $APP_DIR/env as $RUN_USER, pip install,"
    echo "#        collectstatic, migrate, then write and enable this unit:"
    echo "# $UNIT_FILE"
    echo "$unit"
    if [ -z "$(config_value DJANGO_SECRET_KEY)" ]; then
        echo
        echo "# Would append a generated DJANGO_SECRET_KEY to $CONFIG"
    fi
    exit 0
fi

set -e

# A secret key is required with DEBUG off. Generate one once and keep it in the
# config so sessions survive restarts.
if [ -z "$(config_value DJANGO_SECRET_KEY)" ]; then
    secret=$(python3 -c "import secrets; print(secrets.token_urlsafe(50))")
    printf "\n# Generated by install-web.sh. Signs sessions and login codes; keep it secret.\nexport DJANGO_SECRET_KEY='%s'\n" "$secret" >> "$CONFIG"
    echo "Added a generated DJANGO_SECRET_KEY to $CONFIG"
fi

# Python goes in as root; the virtualenv is built as the run user so it owns it
source "$APP_DIR/python-env.sh"
if ! find_python >/dev/null; then
    install_python
    hash -r
fi

sudo -u "$RUN_USER" -H bash <<APP
set -e
cd "$APP_DIR"
mkdir -p tmp
source ./python-env.sh
ensure_env
source env/bin/activate
pip install --upgrade pip
pip install -r requirements.txt
(
    source "$CONFIG" >/dev/null
    export DEBUG="\${DEBUG:-false}"
    python manage.py collectstatic --noinput
    python manage.py migrate
    if ! python manage.py shell -c "import sys; from django.contrib.auth import get_user_model; sys.exit(0 if get_user_model().objects.filter(is_superuser=True).exists() else 1)"; then
        echo
        echo "No admin user exists yet. Create one with:"
        echo "    source $CONFIG && env/bin/python manage.py createsuperuser"
    fi
)
APP

echo "$unit" > "$UNIT_FILE"
chmod 0644 "$UNIT_FILE"
systemctl daemon-reload
systemctl enable "$SERVICE_NAME.service"
systemctl restart "$SERVICE_NAME.service"

echo
echo "Installed $SERVICE_NAME.service. The site runs as $RUN_USER on $BIND and starts on boot."
echo "Status:       systemctl status $SERVICE_NAME"
echo "Follow logs:  journalctl -u $SERVICE_NAME -f"
echo "After a code or config change: sudo systemctl restart $SERVICE_NAME"
echo "Remove it:    sudo $0 --uninstall"
